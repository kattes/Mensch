/// Aktive Sprache. Wird in main.dart per PlatformDispatcher.locales ermittelt.
String _activeLang = 'en';
bool isRtl = false;

/// Setzt die aktive Sprache anhand der System-Locales.
/// Fallback: Englisch. Liefert die gewählte Sprache zurück.
String detectLocale(List<Locale> locales) {
  for (final loc in locales) {
    final lang = loc.languageCode.toLowerCase();
    if (_translations.containsKey(lang)) {
      _activeLang = lang;
      isRtl = lang == 'ar';
      return lang;
    }
  }
  _activeLang = 'en';
  isRtl = false;
  return 'en';
}

/// Aktive Sprache (read-only).
String get activeLang => _activeLang;

/// Übersetzungs-Lookup mit Platzhalter-Substitution {key} → params[key].
/// Fehlt der Schlüssel, wird der englische Wert versucht, danach der Key selbst.
String t(String key, [Map<String, String>? params]) {
  var s = _translations[_activeLang]?[key]
      ?? _translations['en']?[key]
      ?? key;
  if (params != null) {
    params.forEach((k, v) {
      s = s.replaceAll('{$k}', v);
    });
  }
  return s;
}
